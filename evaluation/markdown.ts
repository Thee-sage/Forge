import type { Interval } from "./stats.js";
import type { InsightRow, Rate, SplitSummary } from "./summary.js";

/** Renders report.json as the human-readable REPORT.md. All figures come from the report object. */
interface Failure { caseId: string; split: string; family: string; category: string; check: string; severity: string; ambiguous: boolean; expected?: unknown; actual?: unknown; detail?: string; reproduce: string }
interface Report {
  evaluator: { version: string; oracleVersion: string; rubricVersion: string; datasetVersion: string; targetRate: number; label: string };
  environment: { note?: string | null; node: string; platform: string; forgeCommit: string; forgeSourceModified: boolean; generatedAt: string };
  integrity: { ok: boolean; datasetVersion: string; files: Record<string, { expected: string; actual: string; ok: boolean }> };
  methods: { confidenceIntervals: string; tolerances: string };
  splits: SplitSummary[];
  failures: Failure[];
}

const pct = (x: number): string => (Number.isNaN(x) ? "n/a" : `${(x * 100).toFixed(1)}%`);
const ci = (i: Interval): string => (Number.isNaN(i.lower) ? "n/a" : `[${pct(i.lower)}, ${pct(i.upper)}]`);
const rate = (r: Rate): string => `${r.pass}/${r.n} = ${pct(r.rate)} ${ci(r.ci)}`;
const esc = (x: unknown): string => String(typeof x === "object" ? JSON.stringify(x) : x).replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 140);

function insightTable(rows: InsightRow[]): string {
  const head = "| Finding type | TP | FP | FN | TN | Precision | Recall | F1 (95% bootstrap CI) |\n|---|---:|---:|---:|---:|---:|---:|---|";
  return head + "\n" + rows.map((r) => `| ${r.type} | ${r.tp} | ${r.fp} | ${r.fn} | ${r.tn} | ${pct(r.precision)} | ${pct(r.recall)} | ${pct(r.f1)} ${ci(r.f1Ci)} |`).join("\n");
}

export function renderMarkdown(r: Report): string {
  const L: string[] = [];
  L.push(`# Forge accuracy evaluation - ${r.evaluator.label}`);
  L.push("");
  L.push(`Generated by \`npm run validate:accuracy\`. Every figure below was computed by this run from \`report.json\`; none is hand-written.`);
  L.push("");
  L.push("| | |\n|---|---|");
  L.push(`| Evaluator / oracle / rubric / dataset version | ${r.evaluator.version} / ${r.evaluator.oracleVersion} / ${r.evaluator.rubricVersion} / ${r.evaluator.datasetVersion} |`);
  L.push(`| Forge commit | ${r.environment.forgeCommit}${r.environment.forgeSourceModified ? " (+ uncommitted changes in src/)" : ""} |`);
  if (r.environment.note) L.push(`| Provenance note | ${r.environment.note} |`);
  L.push(`| Node / platform | ${r.environment.node} / ${r.environment.platform} |`);
  L.push(`| Generated at | ${r.environment.generatedAt} |`);
  L.push(`| Dataset integrity (SHA-256 vs MANIFEST.json) | ${r.integrity.ok ? "verified" : "FAILED"} |`);
  L.push(`| Target threshold | ${pct(r.evaluator.targetRate)} (a threshold, not a result) |`);
  L.push("");
  L.push("**How to read this.** The held-out split is the measurement. The dev split is shown for transparency but was used for debugging, so it is *not* an independent result. The datasets are synthetic: these numbers describe behaviour on the defined cases, not on real-world financial data. See `docs/ACCURACY_VALIDATION.md` for definitions, rubric and limitations.");
  L.push("");

  for (const s of r.splits) {
    L.push(`## Split: ${s.split}`);
    L.push("");
    L.push(`${s.cases.pipeline} end-to-end cases, ${s.cases.cells} single-cell parsing cases, ${s.cases.classify} classification items.`);
    L.push("");
    L.push("### Headline measures (each reported separately; there is no single blended score)");
    L.push("");
    L.push("| ID | Measure | Passed / n | Rate | 95% CI | Point estimate >= target? | CI lower bound >= target? |\n|---|---|---:|---:|---|---|---|");
    for (const h of s.headline) L.push(`| ${h.id} | ${h.name} | ${h.pass}/${h.n} | ${pct(h.rate)} | ${ci(h.ci)} | ${h.n === 0 ? "n/a" : h.meetsTarget ? "yes" : "no"} | ${h.n === 0 ? "n/a" : h.lowerBoundMeetsTarget ? "yes" : "no"} |`);
    L.push("");
    L.push(`**Critical failures: ${s.criticalFailures.length}.** A high average never overrides this count.`);
    L.push("");

    L.push("### A. Numerical correctness");
    L.push("");
    L.push(`- Eligible comparisons: ${rate(s.numeric.comparisons)}`);
    L.push(`- ... excluding interpretation-dependent cases: ${rate(s.numeric.comparisonsUnambiguous)}`);
    L.push(`- Cases with every numeric/availability expectation met: ${rate(s.numeric.cases)}`);
    L.push(`- ... excluding interpretation-dependent cases: ${rate(s.numeric.casesUnambiguous)}`);
    const m = s.numeric.magnitude;
    L.push(`- Error magnitude: largest absolute error among *passing* comparisons ${m.maxAbsErrorAmongPassing.toExponential(2)} (float noise); ${m.failing} failing comparison(s)${m.medianRelErrorAmongFailing !== null ? `, median relative error ${m.medianRelErrorAmongFailing.toExponential(2)}, largest absolute error ${m.maxAbsErrorAmongFailing!.toExponential(2)}` : ""}.`);
    L.push(`- Failures by severity (numeric + availability): critical ${s.numeric.failuresBySeverity["critical"]}, major ${s.numeric.failuresBySeverity["major"]}, minor ${s.numeric.failuresBySeverity["minor"]}.`);
    L.push(`- Unavailable-measure expectations (missing data must not become a number): ${rate(s.availability)}`);
    L.push("");
    L.push("| Metric | Passed / n | Rate | Max abs error |\n|---|---:|---:|---:|");
    for (const [k, v] of Object.entries(s.numeric.byMetric).sort()) L.push(`| ${k} | ${v.pass}/${v.n} | ${pct(v.rate)} | ${v.maxAbsError.toExponential(1)} |`);
    L.push("");
    L.push("| Family | Passed / n | Rate |\n|---|---:|---:|");
    for (const [k, v] of Object.entries(s.numeric.byFamily).sort()) L.push(`| ${k} | ${v.pass}/${v.n} | ${pct(v.rate)} |`);
    L.push("");

    L.push("### Cell parsing and classification (human-labelled)");
    L.push("");
    L.push(`- Cells read correctly or safely rejected: ${rate(s.cells.overall)}. Silent corruption (wrong value accepted, or dropped without a record): **${s.cells.silentCorruption}**. Valid cells rejected: ${s.cells.falseRejections}.`);
    for (const [k, v] of Object.entries(s.classify.byKind)) L.push(`- ${k} classification: ${rate(v)}`);
    L.push("");

    L.push("### B. Insight correctness (labelled)");
    L.push("");
    L.push(insightTable([...s.insight.rows, s.insight.micro]));
    L.push("");
    L.push(`Absent labels are *ungraded*, not false negatives. Emissions with no label in their case (reported, not scored): ${Object.entries(s.insight.ungradedEmissions).map(([k, v]) => `${k} x${v}`).join(", ") || "none"}.`);
    L.push("");
    if (s.insight.falsePositives.length) L.push(`False positives: ${s.insight.falsePositives.map((c) => `${c.caseId} (${c.check})`).join(", ")}`);
    if (s.insight.falseNegatives.length) L.push(`\nFalse negatives: ${s.insight.falseNegatives.map((c) => `${c.caseId} (${c.check})`).join(", ")}`);
    L.push("");

    L.push("### C. Evidence grounding");
    L.push("");
    L.push(`- Insight evidence exists in the cited module's published evidence: ${rate(s.grounding.evidenceExists)}`);
    L.push(`- Insight evidence entity/period/value/sign matches the source data: ${rate(s.grounding.evidenceValue)}`);
    L.push(`- Evidence inside module findings matches the source data: ${rate(s.grounding.findingEvidenceValue)}`);
    L.push(`- Observed (directly checkable) claims in insight/scenario text: ${rate(s.grounding.observedClaims)}. **Unsupported: ${s.grounding.unsupportedObserved}.**`);
    L.push(`- Heuristic attributions: ${rate(s.grounding.heuristicClaims)}. **Unsupported: ${s.grounding.unsupportedHeuristic}.**`);
    L.push(`- Hypothetical statements (not checkable, not scored): ${s.grounding.hypotheticalClaims}.`);
    L.push("");
    L.push("| Grounding check | Passed / n |\n|---|---:|");
    for (const [k, v] of Object.entries(s.grounding.byCheck).sort()) L.push(`| ${k} | ${v.pass}/${v.n}${v.na ? ` (+${v.na} n/a)` : ""} |`);
    L.push("");
    L.push("Note: `claim:reserves-being-built` passes whenever net savings are positive, which the rule's own guard already requires, so it is a weak check; read the heuristic-attribution rate with that in mind.");
    L.push("");

    L.push("### D. Data safety, abstention and invariants");
    L.push("");
    L.push(`- Safety expectations met: ${rate(s.safety.overall)}`);
    for (const [k, v] of Object.entries(s.safety.byCheck).sort()) L.push(`  - ${k}: ${v.pass}/${v.n}`);
    L.push(`- Invariants: ${rate(s.invariants.overall)}`);
    for (const [k, v] of Object.entries(s.invariants.byName).sort()) if (v.fail > 0) L.push(`  - FAILING ${k}: ${v.fail}/${v.n}`);
    if (s.safety.declaredUnsupported.length) {
      L.push(`- Declared unsupported (documented limitation; reported, not scored): ${s.safety.declaredUnsupported.map((c) => `${c.caseId} - ${c.actual}`).join("; ")}`);
    }
    L.push("");
  }

  L.push("## Failure listing");
  L.push("");
  L.push("Every failing check with a reproducible case id. Re-run one case with the command shown. `amb` = rests on a documented interpretation.");
  L.push("");
  L.push("| Case | Split | Category | Check | Severity | amb | Expected | Actual | Detail |\n|---|---|---|---|---|---|---|---|---|");
  const order: Record<string, number> = { critical: 0, major: 1, minor: 2 };
  for (const f of [...r.failures].sort((a, b) => (order[a.severity]! - order[b.severity]!) || a.caseId.localeCompare(b.caseId))) {
    L.push(`| ${f.caseId} | ${f.split} | ${f.category} | ${esc(f.check)} | ${f.severity} | ${f.ambiguous ? "y" : ""} | ${esc(f.expected ?? "")} | ${esc(f.actual ?? "")} | ${esc(f.detail ?? "")} |`);
  }
  L.push("");
  L.push("Reproduce any row: `npm run validate:accuracy -- --case <Case>`.");
  L.push("");
  L.push("## Method notes");
  L.push("");
  L.push(`- ${r.methods.confidenceIntervals}`);
  L.push(`- ${r.methods.tolerances}`);
  return L.join("\n") + "\n";
}
